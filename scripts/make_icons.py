# Regenerate include/pwa.h: uv run --with pillow python3 scripts/make_icons.py include/pwa.h
import io, sys
from PIL import Image, ImageDraw
def icon(n):
    s = 4 * n  # supersample
    im = Image.new("RGB", (s, s), (15, 20, 24))
    d = ImageDraw.Draw(im)
    cx, r = s / 2, s * 0.24
    cy = s * 0.58
    d.ellipse([cx - r, cy - r, cx + r, cy + r], fill=(76, 194, 255))
    d.polygon([(cx - r * 0.97, cy - r * 0.25), (cx, s * 0.16), (cx + r * 0.97, cy - r * 0.25)], fill=(76, 194, 255))
    d.ellipse([cx - r * 0.55, cy - r * 0.05, cx - r * 0.2, cy + r * 0.3], fill=(200, 238, 255))
    im = im.resize((n, n), Image.LANCZOS).quantize(16)
    b = io.BytesIO(); im.save(b, "PNG", optimize=True); return b.getvalue()
out = ["#pragma once", "// Home-screen web app: manifest and icons (generated by scripts/make_icons.py).", ""]
for n in (180, 512):
    data = icon(n)
    out.append(f"static const uint8_t ICON_{n}[] PROGMEM = {{" + ",".join(str(x) for x in data) + "};")
    print(n, len(data), file=sys.stderr)
out.append('''static const char MANIFEST[] PROGMEM = R"({"name":"HumidESP","short_name":"HumidESP","start_url":"/","display":"standalone","background_color":"#0f1418","theme_color":"#0f1418","icons":[{"src":"/icon-180.png","sizes":"180x180","type":"image/png"},{"src":"/icon-512.png","sizes":"512x512","type":"image/png","purpose":"any maskable"}]})";''')
open(sys.argv[1], "w").write("\n".join(out) + "\n")
